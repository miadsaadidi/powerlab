/**
 * Lookup regional climate and solar data by state name or code
 */
export function getRegionalDataByState(stateOrCode: string): RegionalClimateData | undefined {
  const query = stateOrCode.toLowerCase().trim();
  return US_REGIONAL_CLIMATE_DATA.find(
    (item) =>
      item.state.toLowerCase() === query ||
      item.stateCode.toLowerCase() === query ||
      item.state.toLowerCase().startsWith(query)
  );
}

/**
 * Filter regional data by search query (state, city, or climate zone)
 */
export function searchRegionalData(query: string): RegionalClimateData[] {
  if (!query || !query.trim()) return US_REGIONAL_CLIMATE_DATA;
  const q = query.toLowerCase().trim();
  return US_REGIONAL_CLIMATE_DATA.filter(
    (item) =>
      item.state.toLowerCase().includes(q) ||
      item.stateCode.toLowerCase().includes(q) ||
      item.metro.toLowerCase().includes(q) ||
      item.ashraeClimateZone.toLowerCase().includes(q)
  );
}
